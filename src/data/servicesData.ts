export const formatCurrencyAmount = (amountInUSD: number, currency: Currency): string => {
  const cfg = CURRENCY_CONFIGS[currency] || CURRENCY_CONFIGS.USD;
  const val = amountInUSD * cfg.rate;
  if (currency === 'NGN') {
    return `${cfg.symbol}${Math.round(val).toLocaleString()}`;
  }
  if (currency === 'XAF' || currency === 'XOF') {
    return `${Math.round(val).toLocaleString()} ${cfg.symbol}`;
  }
  if (currency === 'GHS') {
    return `${cfg.symbol}${val.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  }
  return `${cfg.symbol}${val.toFixed(2)}`;
};
